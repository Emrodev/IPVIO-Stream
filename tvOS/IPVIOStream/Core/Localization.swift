enum Lang: String, Codable, CaseIterable, Hashable, Sendable {
    case en
    case ar

    var locale: Locale { Locale(identifier: rawValue) }

    var layoutDirection: LayoutDirection {
        self == .ar ? .rightToLeft : .leftToRight
    }

    var displayName: String {
        self == .ar ? "العربية" : "English"
    }
}

enum L {
    /// Updated by AppModel whenever the user changes the app language.
    nonisolated(unsafe) static var current: Lang = .en

    static func t(_ key: String) -> String {
        if let value = tables[current]?[key] { return value }
        if let value = tables[.en]?[key] { return value }
        return key
    }

    static func f(_ key: String, _ args: CVarArg...) -> String {
        let format = t(key)
        return String(format: format, locale: current.locale, arguments: args)
